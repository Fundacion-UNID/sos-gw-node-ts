const DIGITAL_TWIN_SUBJECT_ALIAS_SECTION = 'digitaltwin_subject_aliases';
const RESEARCH_PROJECTION_AUTHOR = 'urn:gdc:research-projection';
const DIGITAL_TWIN_SUBJECT_URN_UUID = /^urn:uuid:[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** Private derived search fields. They are never returned in a materialized FHIR resource. */
export const DIGITAL_TWIN_SEARCH_TEXT_CLAIM = '__digitalTwinSearch.text';
export const DIGITAL_TWIN_SEARCH_DATE_CLAIM = '__digitalTwinSearch.date';
export const DIGITAL_TWIN_SEARCH_LANGUAGE_CLAIM = '__digitalTwinSearch.language';
export const DIGITAL_TWIN_SEARCH_CLAIM_PREFIX = '__digitalTwinSearch.';

export type DigitalTwinResearchProjectionResult = Readonly<{
  claims: Record<string, unknown>;
  researchReady: boolean;
  warning?: OperationOutcome;
}>;

export type DigitalTwinSubjectAlias = RecordBase & {
  type: 'digital-twin-subject-alias';
  sourceSubjectHash: string;
  twinSubjectId: string;
  /** Globally scoped study/service reference. Absent only on legacy aliases. */
  researchUseReference?: string;
  createdAt?: string;
  lastSharedAt?: string;
};

const BLOCKED_RESEARCH_CLAIM_SEGMENT = /(?:^|[.\-_])(display|text|title|description|note|instruction|name|address|telecom|contact|narrative)(?:$|[.\-_])/i;
const RESEARCH_IDENTIFIER_CLAIM = /(?:^|\.)(?:id|identifier)(?:\.value)?$/i;
const RESEARCH_PATIENT_CLAIM = /(?:^|\.)patient(?:\.reference)?$/i;
const RESEARCH_SUBJECT_CLAIM = /(?:^|\.)subject(?:\.reference)?$/i;

const RESEARCH_RESOURCE_TYPES = new Set([
  'MedicationStatement', 'Observation', 'AllergyIntolerance', 'Condition',
  'DeviceUseStatement', 'Flag', 'Procedure', 'ImagingStudy', 'Immunization',
  'DiagnosticReport', 'CarePlan', 'Encounter', 'AdverseEvent', 'Composition',
]);

const FINALIZED_OBSERVATION_STATUSES = new Set(['final', 'amended', 'corrected']);
const FINALIZED_COMPOSITION_STATUSES = new Set(['final', 'amended']);

function sourceSubjectHash(sourceSubject: string): string {
  return createHash('sha256').update(String(sourceSubject || '').trim(), 'utf8').digest('hex');
}

/** Builds the private alias key without exposing the operational subject. */
export function buildDigitalTwinSubjectAliasId(sourceSubject: string, researchUseReference?: string): string {
  const normalizedSource = String(sourceSubject || '').trim();
  const normalizedReference = String(researchUseReference || '').trim();
  if (!normalizedSource) throw new Error('sourceSubject is required');
  return sourceSubjectHash(normalizedReference ? `${normalizedSource}|${normalizedReference}` : normalizedSource);
}

function stableResearchUuid(seed: string): string {
  const bytes = createHash('sha256').update(seed, 'utf8').digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export function getDigitalTwinSubjectAliasSectionId(): string {
  return getEnvSectionId(DIGITAL_TWIN_SUBJECT_ALIAS_SECTION);
}

/** Returns whether a subject is a standards-shaped, non-resolvable UUID URN. */
export function isDigitalTwinSubjectId(value: unknown): value is string {
  return DIGITAL_TWIN_SUBJECT_URN_UUID.test(String(value || '').trim());
}

/**
 * Confirms that a UUID URN was generated by this tenant's private alias
 * registry. Syntax alone is insufficient because a caller can invent a UUID.
 */
export async function isRegisteredDigitalTwinSubjectId(input: {
  vaultRepository: IVaultRepository;
  tenantVaultId: string;
  twinSubjectId: string;
}): Promise<boolean> {
  const twinSubjectId = String(input.twinSubjectId || '').trim();
  if (!isDigitalTwinSubjectId(twinSubjectId)) return false;
  const aliases = await input.vaultRepository.getContainersInSection<DigitalTwinSubjectAlias>(
    input.tenantVaultId,
    getDigitalTwinSubjectAliasSectionId(),
  );
  return aliases.some((alias) => alias?.twinSubjectId === twinSubjectId);
}

/**
 * Gets or creates the stable, non-resolvable research subject assigned to one
 * operational individual inside a tenant. The reversible binding remains in
 * the confidential tenant vault and is never copied into the research record.
 */
export async function getOrCreateDigitalTwinSubjectId(input: {
  vaultRepository: IVaultRepository;
  tenantVaultId: string;
  sourceSubject: string;
  researchUseReference?: string;
}): Promise<string> {
  const normalizedSource = String(input.sourceSubject || '').trim();
  if (!normalizedSource) throw new Error('sourceSubject is required');
  const researchUseReference = String(input.researchUseReference || '').trim();
  const id = buildDigitalTwinSubjectAliasId(normalizedSource, researchUseReference);
  const sectionId = getDigitalTwinSubjectAliasSectionId();
  const existing = typeof input.vaultRepository.get === 'function'
    ? await input.vaultRepository.get<DigitalTwinSubjectAlias>(input.tenantVaultId, id, sectionId)
    : undefined;
  if (existing?.twinSubjectId && isDigitalTwinSubjectId(existing.twinSubjectId)) {
    return existing.twinSubjectId;
  }

  const twinSubjectId = `urn:uuid:${randomUUID()}`;
  const createdAt = new Date().toISOString();
  await input.vaultRepository.put<DigitalTwinSubjectAlias>(input.tenantVaultId, [{
    id,
    type: 'digital-twin-subject-alias',
    sourceSubjectHash: sourceSubjectHash(normalizedSource),
    twinSubjectId,
    createdAt,
    ...(researchUseReference ? { researchUseReference } : {}),
  }], sectionId);
  return twinSubjectId;
}

/** Records only the latest successful projection time in the private alias index. */
export async function markDigitalTwinStudyTargetShared(input: {
  vaultRepository: IVaultRepository;
  tenantVaultId: string;
  sourceSubject: string;
  researchUseReference?: string;
  sharedAt?: string;
}): Promise<void> {
  const id = buildDigitalTwinSubjectAliasId(input.sourceSubject, input.researchUseReference);
  const sectionId = getDigitalTwinSubjectAliasSectionId();
  const alias = await input.vaultRepository.get<DigitalTwinSubjectAlias>(input.tenantVaultId, id, sectionId);
  if (!alias?.twinSubjectId) throw new Error('Digital twin study target is not registered');
  await input.vaultRepository.put<DigitalTwinSubjectAlias>(input.tenantVaultId, [{
    ...alias,
    lastSharedAt: input.sharedAt || new Date().toISOString(),
  }], sectionId);
}

export function isDigitalTwinResearchResourceType(resourceType: string): boolean {
  return RESEARCH_RESOURCE_TYPES.has(String(resourceType || '').trim());
}

/**
 * Research accepts clinical-service evidence only. A subject, relative or
 * other personal author may remain in the operational record, but cannot
 * populate the clinical research repository until a professional attests it.
 */
export function isProfessionallyAttestedResearchRecord(claims: Record<string, unknown>): boolean {
  const attesters = String(getClaimValue(claims, 'Composition.attester') || '')
    .split(',').map((value) => value.trim());
  const modes = String(getClaimValue(claims, 'Composition.attester-mode') || '')
    .split(',').map((value) => value.trim().toLowerCase());
  return modes.some((mode, index) => mode === 'professional' && Boolean(attesters[index]));
}

/** Keeps draft measurements and documents in the operational plane only. */
export function isFinalizedDigitalTwinResearchRecord(
  resourceType: string,
  claims: Record<string, unknown>,
): boolean {
  const normalizedType = String(resourceType || '').trim();
  if (normalizedType === ResourceTypesFhirR4.Observation) {
    const status = String(getClaimValue(claims, 'Observation.status') || '').trim().toLowerCase();
    return FINALIZED_OBSERVATION_STATUSES.has(status);
  }
  if (normalizedType === ResourceTypesFhirR4.Composition) {
    const status = String(getClaimValue(claims, 'Composition.status') || '').trim().toLowerCase();
    return FINALIZED_COMPOSITION_STATUSES.has(status);
  }
  return true;
}

/**
 * Builds the permitted research projection for one clinical resource.
 *
 * Terminology identity remains usable across days and systems: canonical
 * `system|code`, the selected display, confirmed local text and language
 * survive as source evidence. These received labels are not authoritative;
 * research normalization re-resolves standardized terminology from the code.
 * Direct identifiers are replaced, subject
 * references are rebound to the registered research UUID, and arbitrary
 * identifying narrative is excluded. Private query helpers added to the
 * returned storage record are never part of a materialized FHIR response.
 */
export function projectClaimsForDigitalTwin(input: {
  claims: Record<string, unknown>;
  resourceType: string;
  twinSubjectId: string;
  terminology?: ResolvedResearchTerminology;
}): Record<string, unknown> {
  const resourceType = String(input.resourceType || '').trim();
  const twinSubjectId = String(input.twinSubjectId || '').trim();
  if (!isDigitalTwinResearchResourceType(resourceType)) {
    throw new Error(`Resource type '${resourceType}' is not allowed in digital twin research projection.`);
  }
  if (!twinSubjectId) throw new Error('twinSubjectId is required');

  const terminologyCodeClaim = getResearchTerminologyCodeClaim(resourceType);
  const hasTerminologyCode = Boolean(
    terminologyCodeClaim && String(getClaimValue(input.claims, terminologyCodeClaim) || '').trim(),
  );
  const usesVaccineCode = resourceType === ResourceTypesFhirR4.Immunization;
  const sourceTextClaim = `${resourceType}.${usesVaccineCode ? 'vaccine-code-text' : 'code-text'}`;
  const sourceDisplayClaim = `${resourceType}.${usesVaccineCode ? 'vaccine-code-display' : 'code-display'}`;
  const isUncodedMedication = resourceType === ResourceTypesFhirR4.MedicationStatement && !hasTerminologyCode;
  const mayUseClinicalFallback = isUncodedMedication
    && !input.terminology
    && isProfessionallyAttestedResearchRecord(input.claims);
  const clinicalFallbackText = mayUseClinicalFallback
    ? String(getClaimValue(input.claims, sourceTextClaim) || '').trim()
    : '';
  const clinicalFallbackDisplay = mayUseClinicalFallback
    ? String(getClaimValue(input.claims, sourceDisplayClaim) || '').trim()
    : '';
  const searchableText = Array.from(new Set([
    ...Object.entries(input.claims || {})
      .filter(([key]) => /\.code$/i.test(String(key || '').trim()))
      .map(([, value]) => String(value || '').trim()),
    String(input.terminology?.text || '').trim(),
    String(input.terminology?.display || '').trim(),
    clinicalFallbackText,
    clinicalFallbackDisplay,
  ].filter(Boolean)));
  const searchableDate = Object.entries(input.claims || {})
    .filter(([key]) => /\.(?:effective(?:-?datetime)?|issued|recorded(?:date|on)?|occurrence-?datetime|onset-?datetime|performed-?datetime|date|datetime|period-start)$/i.test(String(key || '').trim()))
    .map(([, value]) => String(value || '').trim())
    .find((value) => Boolean(value) && !Number.isNaN(Date.parse(value)));
  const searchableLanguage = Object.entries(input.claims || {})
    .find(([key]) => /\.language$/i.test(String(key || '').trim()))?.[1];

  const projected: Record<string, unknown> = {};
  for (const [key, rawValue] of Object.entries(input.claims || {})) {
    const normalizedKey = String(key || '').trim();
    if (!normalizedKey) continue;
    if (normalizedKey === '@context') { projected[normalizedKey] = rawValue; continue; }
    // Caller labels are operational source evidence, never authoritative
    // research terminology. A professionally attested clinical service is the
    // explicit fallback when the governed resolver cannot supply a label.
    if (/\.code-(?:display|text)$/i.test(normalizedKey)) {
      continue;
    }
    if (isUncodedMedication && /(?:^|\.)MedicationStatement\.user-selected$/i.test(normalizedKey)) {
      projected[normalizedKey] = 'false';
      continue;
    }
    if (BLOCKED_RESEARCH_CLAIM_SEGMENT.test(normalizedKey)) continue;
    if (RESEARCH_PATIENT_CLAIM.test(normalizedKey)) continue;
    if (RESEARCH_SUBJECT_CLAIM.test(normalizedKey)) { projected[normalizedKey] = twinSubjectId; continue; }
    if (/\.author$/i.test(normalizedKey)) { projected[normalizedKey] = RESEARCH_PROJECTION_AUTHOR; continue; }
    if (RESEARCH_IDENTIFIER_CLAIM.test(normalizedKey)) {
      projected[normalizedKey] = `urn:uuid:${stableResearchUuid(`${twinSubjectId}|${resourceType}|${normalizedKey}|${String(rawValue || '')}`)}`;
      continue;
    }
    projected[normalizedKey] = rawValue;
  }
  if (input.terminology?.text) projected[input.terminology.textClaim] = input.terminology.text;
  if (input.terminology?.display) projected[input.terminology.displayClaim] = input.terminology.display;
  if (clinicalFallbackText) projected[sourceTextClaim] = clinicalFallbackText;
  if (clinicalFallbackDisplay) projected[sourceDisplayClaim] = clinicalFallbackDisplay;
  if (
    isUncodedMedication
    && !Object.keys(projected).some((key) => /(?:^|\.)MedicationStatement\.user-selected$/i.test(key))
  ) {
    projected['MedicationStatement.user-selected'] = 'false';
  }
  if (searchableText.length > 0) projected[DIGITAL_TWIN_SEARCH_TEXT_CLAIM] = searchableText.join('\u001f');
  if (searchableDate) projected[DIGITAL_TWIN_SEARCH_DATE_CLAIM] = searchableDate;
  const normalizedLanguage = input.terminology?.textLanguage || searchableLanguage;
  if (normalizedLanguage) projected[DIGITAL_TWIN_SEARCH_LANGUAGE_CLAIM] = String(normalizedLanguage).trim();
  return projected;
}

/** Resolves governed terminology before building a research projection. */
export async function resolveAndProjectClaimsForDigitalTwin(input: {
  claims: Record<string, unknown>;
  resourceType: string;
  twinSubjectId: string;
  sector: string;
  jurisdiction: string;
}): Promise<DigitalTwinResearchProjectionResult> {
  let terminology: ResolvedResearchTerminology | undefined;
  let warning: OperationOutcome | undefined;
  const codeClaim = getResearchTerminologyCodeClaim(input.resourceType);
  const hasCode = Boolean(codeClaim && String(getClaimValue(input.claims, codeClaim) || '').trim());
  const labelsEnabled = String(process.env.RESEARCH_TERMINOLOGY_LABELS_ENABLED || 'false')
    .trim().toLowerCase() === 'true';
  let researchReady = Boolean(codeClaim && hasCode && !labelsEnabled);
  try {
    terminology = labelsEnabled ? await resolveResearchTerminologyLabels(input) : undefined;
    if (codeClaim && !hasCode) {
      warning = createOperationOutcome(
        IssueLevel.Warning,
        IssueType.Incomplete,
        `${input.resourceType} terminology requires professional review because its canonical code is missing.`,
      );
    } else if (labelsEnabled && codeClaim && !terminology) {
      warning = createOperationOutcome(
        IssueLevel.Warning,
        IssueType.Processing,
        `${input.resourceType} terminology labels are temporarily unavailable.`,
      );
    } else if (codeClaim && hasCode) researchReady = true;
  } catch (error) {
    // Clinical ingestion must not report failure after its operational record
    // has already been committed. Keep the exact code-only projection and make
    // the missing normalization observable for later reconciliation.
    console.error('[ResearchTerminology] Exact-label resolution failed; projecting canonical code only.', error);
    warning = createOperationOutcome(
      IssueLevel.Warning,
      IssueType.Processing,
      `${input.resourceType} terminology labels are temporarily unavailable.`,
    );
  }
  const claims = projectClaimsForDigitalTwin({
    claims: input.claims,
    resourceType: input.resourceType,
    twinSubjectId: input.twinSubjectId,
    ...(terminology ? { terminology } : {}),
  });
  return { claims, researchReady, ...(warning ? { warning } : {}) };
}
